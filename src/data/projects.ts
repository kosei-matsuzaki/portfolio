export type Kind = "work" | "research" | "internship";
export type Category = "ai" | "game" | "app" | "research";

/** 分類の表示名。色は持たない（色は作品自身から借りる。docs/design.md） */
export const categoryMeta: Record<Category, { label: string }> = {
  ai: { label: "AI・機械学習" },
  game: { label: "ゲーム・グラフィックス" },
  app: { label: "アプリ・Web" },
  research: { label: "研究" },
};

export type ProjectLink = {
  label: string;
  href: string;
  kind: "repo" | "demo" | "doc" | "store";
};

/**
 * リンクの種類ごとの見せ方。一覧カードは label（「ブラウザで試す（デモ）」など）が
 * 長すぎるので short に差し替え、詳細ページでは主役のリンクだけボタンを強調する。
 * Record なので、kind を足すとここを埋めるまで型が通らない。
 */
export const linkMeta: Record<
  ProjectLink["kind"],
  { short: string; primary: boolean }
> = {
  repo: { short: "GitHub", primary: false },
  demo: { short: "デモ", primary: true },
  doc: { short: "資料", primary: false },
  store: { short: "App Store", primary: true },
};

export type Shot = { src: string; alt: string; caption: string };

/** 図版。動画があれば静止画（poster）の上で再生し、無ければ静止画だけを出す */
export type Media = {
  /** ポスター兼フォールバックの静止画（/images/... ） */
  poster: string;
  /** ループ再生する無音動画（/video/... ）。省略可 */
  video?: string;
  alt: string;
  caption?: string;
  /** スマホ画面など縦長の図版。16:10 に収めず、実寸の比率のまま高さで置く */
  portrait?: boolean;
};

export type Section = {
  heading: string;
  body?: string[];
  /** media を持たせると、図版と説明を交互に並べる形で描画される */
  bullets?: { title?: string; text: string; media?: Media }[];
  table?: { headers: string[]; rows: string[][]; caption?: string };
  figure?: { src: string; alt: string; caption: string; light?: boolean };
};

export type Project = {
  slug: string;
  kind: Kind;
  category: Category;
  title: string;
  subtitle: string;
  /** 一覧カード用の短い説明（2〜3文） */
  summary: string;
  period: string;
  role: string;
  stack: string[];
  /** カード裏に出す短い見どころ */
  highlights: string[];
  metrics: { value: string; label: string }[];
  links: ProjectLink[];
  /**
   * その作品の画面から取った色 1 つ（番号・レール・リンクの下線に使う）。
   * 画像を載せていない作品は持たない = 借りる先が無いので色を作らない。
   * 選び方は docs/design.md「作品の色」。
   */
  accent?: string;
  /** リポジトリ非公開などの注記 */
  note?: string;
  /** 主図版。指定すると一覧カバーと詳細ページ冒頭がこれになる（cover より優先） */
  media?: Media;
  cover?: Shot;
  shots?: Shot[];
  video?: { src: string; poster: string; caption: string };
  sections: Section[];
  aiUsage?: string[];
};

